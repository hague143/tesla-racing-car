import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = file => readFile(resolve(root, file), 'utf8');
let html = await read('public/index.html');
const script = html.match(/<script[^>]+src="([^"]+)"[^>]*><\/script>/);
const style = html.match(/<link[^>]+rel="stylesheet"[^>]+href="([^"]+)"[^>]*>/);
if (!script || !style) throw new Error('Build the Vite project before exporting');
const bundle = (await read('public/' + script[1])).replace(/<\/script/gi, text => text.replace('/', '\\/'));
html = html.replace(script[0], () => `<script type="module">\n${bundle}\n</script>`);
const css = await read('public/' + style[1]);
html = html.replace(style[0], () => `<style>\n${css}\n</style>`);
html += `\n<!-- Third-party license\n${await read('THIRD_PARTY_LICENSES.txt')}\n-->\n`;
const output = resolve(process.argv[2] || '/workspace/library-files/tesla-night-shift.html');
await mkdir(dirname(output), { recursive: true }); await writeFile(output, html);
console.log(`Exported ${output} (${Buffer.byteLength(html).toLocaleString()} bytes)`);
